  home: 'house',
  search: 'search',
  library: 'library-big',
  browse: 'layout-grid',
  chart: 'chart-no-axes-column',
  dice: 'dices',
  settings: 'settings',
  user: 'circle-user-round',
  play: 'play',
  pause: 'pause',
